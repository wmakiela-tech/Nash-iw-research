#!/usr/bin/env python3
"""INT8 ROT047: completely source- and NumPy-free independent exact rational tensor calculation."""
import argparse, json
from pathlib import Path
import sympy as S
from itertools import product

def TT(H,m):
  m=S.Matrix(m);Q=S.eye(3)-m*m.T/(m.dot(m))
  return S.simplify(Q*H*Q-S.trace(Q*H)*Q/2)
def sym(a,b):return a*b.T+b*a.T

def main():
  ap=argparse.ArgumentParser();ap.add_argument('--out',required=True);ar=ap.parse_args()
  x,y=S.symbols('s1 s2',real=True);d=2*x-y
  k=S.Matrix([1,2,0]);l=S.Matrix([1,1,0]);z=S.Matrix([0,0,1])
  sk=S.Matrix([x,y,0]);sl=S.Matrix([x,x,0]);r=S.simplify((S.eye(3)-k*k.T/k.dot(k))*sk)
  assert r==d*S.Matrix([2,-1,0])/5
  assert TT(sym(sl,z),l)==S.zeros(3)
  assert TT(sym(sk,z),k)==sym(r,z)
  # Projected second Lie tensor, generated by the z-shear Jacobian, no spatial derivative product rule.
  H=sym(r,sl)
  plus=S.Matrix([2,3,0]);minus=S.Matrix([0,1,0]);wp=S.Matrix([3,-2,0]);wm=S.Matrix([1,0,0]);
  wp=wp/S.sqrt(13); Wp=wp*wp.T-z*z.T;Wm=wm*wm.T-z*z.T
  pp=S.simplify(TT(H,plus));pm=S.simplify(TT(H,minus))
  assert S.simplify(pp-(8*x*d/S.Integer(65))*Wp)==S.zeros(3)
  assert S.simplify(pm-(2*x*d/S.Integer(5))*Wm)==S.zeros(3)
  # cosine k cos l => 1/2 sidebands. Norm of each tensor W is sqrt2 and cos RMS 1/sqrt2.
  cp=-4*x*d/S.Integer(65);cm=-x*d/S.Integer(5)
  assert S.simplify(cp**2+cm**2-x*x*d*d*S.Rational(185,4225))==0
  assert S.simplify(S.trace(Wp.T*Wp)-2)==0 and S.trace(Wm.T*Wm)==2
  # Source nonprojected commutator: Lf(Lg(I))=sym(grad f,grad g)=Lg(Lf(I)).
  assert sym(sk,sl)==sym(sl,sk)
  # independent rational samples for arbitrary gradient symbols, two Fourier sidebands.
  checks=0;positive=0
  for a,b in product(range(-6,7),repeat=2):
    ra=r.subs({x:a,y:b}); Ha=H.subs({x:a,y:b})
    assert TT(sym(S.Matrix([a,b,0]),z),k)==sym(ra,z)
    assert TT(Ha,plus)==pp.subs({x:a,y:b})
    assert TT(Ha,minus)==pm.subs({x:a,y:b})
    checks+=1
    if a*(2*a-b):positive+=1
  assert checks==169
  out={'artifact_id':'IW_INT8_ROT047_INSERTED_P_COMMUTATOR_CLOSURE_001_20261029','status':'EXACT_SYMPY_PASS','rational_gradient_checks':checks,'nonzero_mode_witnesses':positive,'source':'NONE_INDEPENDENT','plus_coefficient':'-4*s1*(2*s1-s2)/65','minus_coefficient':'-s1*(2*s1-s2)/5','rms2_coefficient':'185/4225 * s1^2 * (2*s1-s2)^2','N2_rms_limit':'4*pi^2*sqrt(185)/65','restriction':'N odd >=7 for unwrapped sum k+l=(2,3,0); E_mode Identity; constant h=I; source auxiliary full-lattice K_A_out not historical masked K_A'}
  Path(ar.out).write_text(json.dumps(out,sort_keys=True,indent=2,ensure_ascii=False)+'\n',encoding='utf8')
  print('EXACT_SYMPY_PASS',checks,'symbolic identities and rational cases')
if __name__=='__main__':main()
